test("Enter and Backspace cannot restructure the document", async ({ page }) => {
  await login(page, ADMIN);
  const { id, file, frame } = await openEditor(page);
  const before = await source(page, id, file);

  const lead = frame.locator("p.lead");

  // Enter is swallowed wherever the caret is, so this needs no positioning.
  await lead.click();
  await page.keyboard.press("Enter");

  /* Backspace only means "merge with what came before" AT THE START, so the
     caret has to genuinely be there. Clicking the left edge and then WAITING
     for the browser to report a collapsed selection at offset 0 is the only
     reliable way: ProseMirror syncs the DOM selection asynchronously, so a
     Backspace sent too early lands mid-word and deletes a real character —
     which is a perfectly good edit, and nothing to do with what is being
     tested here. */
  await lead.click({ position: { x: 1, y: 8 } });
  await expect
    .poll(() =>
      lead.evaluate(() => {
        const s = getSelection();
        return !!s && s.isCollapsed && s.anchorOffset === 0;
      }),
    )
    .toBe(true);
  await page.keyboard.press("Backspace");

  // No new element, no merged element, no change at all.
  await expectUnchanged(page, id, file, before);
});

